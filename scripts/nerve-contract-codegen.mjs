import { readFile, writeFile } from 'node:fs/promises'

const [, , command, inputPath, outputPath] = process.argv
if (!command || !inputPath || !outputPath || !['generate', 'parse'].includes(command)) {
  throw new Error('Usage: node nerve-contract-codegen.mjs <generate|parse> <input> <output>')
}

const source = await readFile(inputPath, 'utf8')
if (command === 'generate') {
  const project = JSON.parse(source)
  const { mkdir } = await import('node:fs/promises')
  await mkdir(outputPath, { recursive: true })
  for (const service of project.Services ?? []) await writeFile(`${outputPath}/${service.Name}.luau`, `${generateService(service).join('\n').trim()}\n`)
  for (const controller of project.Controllers ?? []) await writeFile(`${outputPath}/${controller.Name}.luau`, `${generateController(controller).join('\n').trim()}\n`)
} else {
  await writeFile(outputPath, JSON.stringify(parseLuau(source), null, 2) + '\n')
}

function generateLuau(project) {
  const lines = ['--!strict', '', '-- Generated by nerve-contract-codegen.mjs. Do not edit by hand.', 'local ReplicatedStorage = game:GetService("ReplicatedStorage")', 'local Nerve = require(ReplicatedStorage.Nerve)', 'local S = Nerve.Schema', '']
  for (const service of project.Services ?? []) lines.push(...generateService(service), '')
  for (const controller of project.Controllers ?? []) lines.push(...generateController(controller), '')
  return `${lines.join('\n').trim()}\n`
}

function generateService(service) {
  const lines = prelude()
  lines.push(`local ${service.Name} = Nerve.CreateService({`, `\tName = ${quote(service.Name)},`, '\tClient = {')
  for (const signal of service.Signals ?? []) lines.push(`\t\t${signal.Name} = ${signalExpression(signal)},`)
  lines.push('\t},', '\tNetwork = {')
  for (const method of service.Methods ?? []) lines.push(`\t\t${method.Name} = ${methodExpression(method)},`)
  lines.push('\t},', '})', '')
  for (const method of service.Methods ?? []) {
    const params = schemaTupleArity(method.Request)
    const args = Array.from({ length: params }, (_, index) => `value${index + 1}`).join(', ')
    lines.push(`function ${service.Name}.Client:${method.Name}(_player: Player${args ? `, ${args}` : ''})`, '\t-- Implement the authoritative server behavior here.', '\treturn nil', 'end', '')
  }
  if (service.Lifecycle?.NerveInit) lines.push(`function ${service.Name}:NerveInit()`, 'end', '')
  if (service.Lifecycle?.NerveStart) lines.push(`function ${service.Name}:NerveStart()`, 'end', '')
  lines.push(`return ${service.Name}`)
  return lines
}

function generateController(controller) {
  const lines = prelude()
  lines.push(`local ${controller.Name} = Nerve.CreateController({`, `\tName = ${quote(controller.Name)},`, '})', '')
  if (controller.Lifecycle?.NerveInit) {
    lines.push(`function ${controller.Name}:NerveInit()`, ...dependencyLines(controller, '\t'), 'end', '')
  }
  if (controller.Lifecycle?.NerveStart) {
    lines.push(`function ${controller.Name}:NerveStart()`, ...dependencyLines(controller, '\t'), 'end', '')
  }
  lines.push(`return ${controller.Name}`)
  return lines
}

function prelude() {
  return ['--!strict', '', '-- Generated by nerve-contract-codegen.mjs. Do not edit by hand.', 'local ReplicatedStorage = game:GetService("ReplicatedStorage")', 'local Nerve = require(ReplicatedStorage.Nerve)', 'local S = Nerve.Schema', '']
}

function dependencyLines(controller, indent) {
  return [...(controller.ServiceDependencies ?? []).map((name) => `${indent}local ${name} = Nerve.GetService(${quote(name)})`), ...(controller.ControllerDependencies ?? []).map((name) => `${indent}local ${name} = Nerve.GetController(${quote(name)})`)]
}

function methodExpression(method) {
  const options = [`Request = ${schemaExpression(method.Request)}`, `Response = ${schemaExpression(method.Response)}`]
  if (method.Timeout !== undefined) options.push(`Timeout = ${method.Timeout}`)
  if (method.RateLimit === false) options.push('RateLimit = false')
  else if (method.RateLimit) options.push(`RateLimit = { Requests = ${method.RateLimit.Requests}, Window = ${method.RateLimit.Window} }`)
  return `Nerve.Method({ ${options.join(', ')} })`
}

function signalExpression(signal) {
  const options = []
  if (signal.Direction) options.push(`Direction = ${quote(signal.Direction)}`)
  if (signal.Reliability) options.push(`Reliability = ${quote(signal.Reliability)}`)
  const suffix = options.length ? `, { ${options.join(', ')} }` : ''
  return `Nerve.Signal(${schemaExpression(signal.Arguments)}${suffix})`
}

function schemaExpression(schema) {
  if (schema.kind === 'optional' || schema.kind === 'array') return `S.${capitalize(schema.kind)}(${schemaExpression(schema.value)})`
  if (schema.kind === 'map') return `S.Map(${schemaExpression(schema.key)}, ${schemaExpression(schema.value)})`
  if (schema.kind === 'struct') return `S.Struct({ ${Object.entries(schema.fields).map(([name, value]) => `${name} = ${schemaExpression(value)}`).join(', ')} })`
  if (schema.kind === 'tuple') return `S.Tuple({ ${schema.items.map(schemaExpression).join(', ')} })`
  return `S.${({ bool: 'Boolean', string: 'String', float64: 'Float64', int32: 'Int32' }[schema.kind] ?? capitalize(schema.kind))}`
}

function schemaTupleArity(schema) { return schema.kind === 'tuple' ? schema.items.length : 1 }
function capitalize(value) { return value[0].toUpperCase() + value.slice(1) }
function quote(value) { return JSON.stringify(value) }

function parseLuau(source) {
  const serviceMatch = source.match(/local\s+(\w+)\s*=\s*Nerve\.CreateService\s*\({[\s\S]*?Name\s*=\s*["']([^"']+)["']/)
  const controllerMatch = source.match(/local\s+(\w+)\s*=\s*Nerve\.CreateController\s*\({[\s\S]*?Name\s*=\s*["']([^"']+)["']/)
  const methods = [...source.matchAll(/function\s+\w+\.Client:(\w+)\s*\(/g)].map((match) => ({ Name: match[1], Kind: 'Method' }))
  const signals = [...source.matchAll(/(\w+)\s*=\s*Nerve\.Signal\s*\(/g)].map((match) => ({ Name: match[1], Kind: 'Signal' }))
  const hooks = [...source.matchAll(/function\s+\w+:(NerveInit|NerveStart)\s*\(/g)].map((match) => match[1])
  const dependencies = [...source.matchAll(/Nerve\.Get(Service|Controller)\(["']([^"']+)["']\)/g)].map((match) => ({ Kind: match[1], Name: match[2] }))
  return { Service: serviceMatch ? { Name: serviceMatch[2], Variable: serviceMatch[1], Methods: methods, Signals: signals, Lifecycle: [...new Set(hooks)] } : undefined, Controller: controllerMatch ? { Name: controllerMatch[2], Variable: controllerMatch[1], Dependencies: dependencies, Lifecycle: [...new Set(hooks)] } : undefined }
}
